"""Reproduce the Prophet section of the ProLoaF benchmark notebook.

The frozen paper notebook, ``Train and Benchmark Models.ipynb``, fits one
Facebook Prophet model on the first 80% of OPSD and makes one continuous
hourly forecast.  It then turns that series into overlapping 24-hour forecast
windows.  This script makes that procedure executable, reproducible, and
auditable without modifying the paper source.

Two results are deliberately exported:

* ``paper_literal_80pct`` follows the notebook literally, including its
  80% default Prophet interval and its 147-hour window offset.
* ``chronological_aligned_95pct`` uses the same single fitted Prophet model,
  but aligns every forecast window with the timestamps of its actual values
  and requests a 95% interval.  This is the meaningful result to place next
  to the reproduced LSTM's 95% test-set evaluation.

The point forecasts are generated by the same fitted Prophet model in both
cases.  Only the interval confidence level and forecast/actual alignment
differ.  Prophet sees the first 80% of the data as in the paper notebook;
the current LSTM checkpoint was selected using a 60/20/20 split.  Therefore
the comparison CSV is explicitly labelled as indicative, not a strictly fair
same-training-budget ranking.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from prophet import Prophet
from prophet.serialize import model_to_json


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATA = ROOT / "paper_source" / "data" / "opsd.csv"
DEFAULT_CONFIG = ROOT / "paper_source" / "targets" / "opsd" / "config.json"
DEFAULT_LSTM_METRICS = (
    ROOT / "artifacts" / "paper_reproduction" / "evaluation" / "opsd_recurrent.csv"
)
DEFAULT_OUTPUT = ROOT / "artifacts" / "paper_reproduction" / "prophet_paper_protocol"

PAPER_TRAIN_SPLIT = 0.80
PAPER_MAX_ORIGINS = 365 * 24


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--lstm-metrics", type=Path, default=DEFAULT_LSTM_METRICS)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    return parser.parse_args()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def make_target_windows(values: np.ndarray, history: int, horizon: int) -> np.ndarray:
    """Match TimeSeriesData: discard history, then return rolling target windows."""
    origins = len(values) - history - horizon + 1
    if origins <= 0:
        raise ValueError("Not enough rows to make a history/forecast window.")
    return np.lib.stride_tricks.sliding_window_view(values[history:], horizon)[:origins]


def evaluate(actual: np.ndarray, prediction: np.ndarray, lower: np.ndarray, upper: np.ndarray, alpha: float):
    """Compute the metric subset shared with the existing baseline runner."""
    errors = actual - prediction
    interval_width = upper - lower
    # This strict lower / inclusive upper condition matches proloaf.metrics.Picp.
    coverage = (actual > lower) & (actual <= upper)
    under = np.maximum(lower - actual, 0.0)
    over = np.maximum(actual - upper, 0.0)
    interval_score = interval_width + (2.0 / alpha) * (under + over)

    overall = {
        "Mse": float(np.mean(errors**2)),
        "Rmse": float(np.sqrt(np.mean(errors**2))),
        "Mae": float(np.mean(np.abs(errors))),
        "Picp": float(np.mean(coverage) * 100.0),
        "Sharpness": float(np.mean(interval_width)),
        "Mis": float(np.mean(interval_score)),
        "Residuals": float(np.mean(errors)),
    }
    by_horizon = pd.DataFrame(
        {
            "horizon_hour": np.arange(1, actual.shape[1] + 1),
            "Mse": np.mean(errors**2, axis=0),
            "Rmse": np.sqrt(np.mean(errors**2, axis=0)),
            "Mae": np.mean(np.abs(errors), axis=0),
            "Picp": np.mean(coverage, axis=0) * 100.0,
            "Sharpness": np.mean(interval_width, axis=0),
            "Mis": np.mean(interval_score, axis=0),
            "Residuals": np.mean(errors, axis=0),
        }
    )
    return overall, by_horizon


def add_mw_columns(frame: pd.DataFrame, scale_range_mw: float) -> pd.DataFrame:
    """Add MW units while retaining normalized metrics for source-code traceability."""
    result = frame.copy()
    if "Mse" in result:
        result["Mse_MW2"] = result["Mse"] * scale_range_mw**2
    for name in ("Rmse", "Mae", "Sharpness", "Mis", "Residuals"):
        if name in result:
            result[f"{name}_MW"] = result[name] * scale_range_mw
    return result


def read_lstm_reference(path: Path, train_target_range_mw: float) -> dict[str, object]:
    """Read the prior LSTM evaluation only as an explicitly non-identical reference."""
    if not path.exists():
        raise FileNotFoundError(f"LSTM metrics not found: {path}")
    row = pd.read_csv(path, sep=";", index_col=0).iloc[0]
    values = {name: float(row[name]) for name in ("Mse", "Rmse", "Mae", "Picp", "Sharpness", "Mis", "Residuals")}
    values.update(
        {
            "model": "ProLoaF-LSTM (existing checkpoint)",
            "protocol": "Existing 60/20/20 LSTM evaluation; 95% Gaussian interval",
            "comparison_status": "Reference only: Prophet used paper's 80/20 fit/evaluation split.",
            "interval_nominal_percent": 95.0,
            "forecast_origins": 8595,
        }
    )
    return add_mw_columns(pd.DataFrame([values]), train_target_range_mw).iloc[0].to_dict()


def save_first_day_plot(frame: pd.DataFrame, path: Path) -> None:
    fig, axis = plt.subplots(figsize=(12, 5))
    axis.plot(frame["timestamp"], frame["actual_MW"], color="black", linewidth=2, label="Actual")
    axis.plot(frame["timestamp"], frame["prediction_MW"], color="#1f77b4", linewidth=2, label="Prophet")
    axis.fill_between(
        frame["timestamp"],
        frame["lower_95_MW"],
        frame["upper_95_MW"],
        color="#1f77b4",
        alpha=0.20,
        label="95% prediction interval",
    )
    axis.set_title("Prophet: first aligned 24-hour forecast window")
    axis.set_xlabel("Timestamp")
    axis.set_ylabel("German load (MW)")
    axis.grid(alpha=0.25)
    axis.legend()
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def main() -> None:
    args = parse_args()
    for path in (args.data, args.config, args.lstm_metrics):
        if not path.exists():
            raise FileNotFoundError(path)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    config = json.loads(args.config.read_text(encoding="utf-8"))
    target = config["target_id"][0]
    history = int(config["history_horizon"])
    horizon = int(config["forecast_horizon"])

    raw = pd.read_csv(args.data, sep=";", index_col=0, parse_dates=True)
    if target not in raw.columns or raw[target].isna().any() or not raw.index.is_monotonic_increasing:
        raise ValueError("OPSD target must exist, be complete, and be in chronological order.")

    # This is intentionally the paper notebook's preprocessing order: fit scaling
    # before the 80/20 split.  It is retained for source fidelity and documented
    # as a limitation in metadata.
    global_min = float(raw[target].min())
    global_max = float(raw[target].max())
    global_range = global_max - global_min
    if global_range <= 0:
        raise ValueError("Target has zero range.")
    scaled_target = (raw[target] - global_min) / global_range

    split_at = int(len(raw) * PAPER_TRAIN_SPLIT)
    train = pd.DataFrame({"ds": raw.index[:split_at], "y": scaled_target.iloc[:split_at].to_numpy()})
    test_index = raw.index[split_at:]
    test_scaled = scaled_target.iloc[split_at:].to_numpy(dtype=float)
    actual_windows = make_target_windows(test_scaled, history, horizon)
    num_origins = min(PAPER_MAX_ORIGINS, len(actual_windows))
    actual_windows = actual_windows[:num_origins]
    if num_origins != 8595:
        raise RuntimeError(f"Expected 8595 OPSD validation windows, got {num_origins}.")

    print("Fitting one Prophet model on the first 80% of OPSD (paper protocol)...")
    started = time.perf_counter()
    model = Prophet(interval_width=0.80)
    model.fit(train)
    fit_seconds = time.perf_counter() - started

    # Forecast the complete final 20%.  The literal notebook uses only the first
    # NUM_PRED + horizon values; the aligned protocol additionally needs history
    # values so that forecast and target windows share timestamps.
    future = model.make_future_dataframe(periods=len(test_index), freq="h", include_history=False)
    forecast_80 = model.predict(future)
    model.interval_width = 0.95
    forecast_95 = model.predict(future)
    predict_seconds = time.perf_counter() - started - fit_seconds

    yhat_80 = forecast_80["yhat"].to_numpy()
    lower_80 = forecast_80["yhat_lower"].to_numpy()
    upper_80 = forecast_80["yhat_upper"].to_numpy()
    yhat_95 = forecast_95["yhat"].to_numpy()
    lower_95 = forecast_95["yhat_lower"].to_numpy()
    upper_95 = forecast_95["yhat_upper"].to_numpy()

    # Literal paper notebook: forecast windows begin at the test split, while
    # y_val_1D begins after history_horizon.  This intentional export is evidence
    # of what the notebook does, not the recommended score for the report.
    literal_prediction = np.lib.stride_tricks.sliding_window_view(yhat_80, horizon)[:num_origins]
    literal_lower = np.lib.stride_tricks.sliding_window_view(lower_80, horizon)[:num_origins]
    literal_upper = np.lib.stride_tricks.sliding_window_view(upper_80, horizon)[:num_origins]
    literal_metrics, literal_horizon = evaluate(
        actual_windows, literal_prediction, literal_lower, literal_upper, alpha=0.20
    )

    # Chronological version: both forecast and actual start after the same 147 h
    # context.  This allows a valid 24 h forecast comparison with the LSTM test set.
    aligned_slice = slice(history, history + num_origins + horizon - 1)
    aligned_prediction = np.lib.stride_tricks.sliding_window_view(yhat_95[aligned_slice], horizon)[:num_origins]
    aligned_lower = np.lib.stride_tricks.sliding_window_view(lower_95[aligned_slice], horizon)[:num_origins]
    aligned_upper = np.lib.stride_tricks.sliding_window_view(upper_95[aligned_slice], horizon)[:num_origins]
    aligned_metrics, aligned_horizon = evaluate(
        actual_windows, aligned_prediction, aligned_lower, aligned_upper, alpha=0.05
    )

    rows = [
        {
            "model": "Facebook Prophet",
            "protocol": "paper_literal_80pct",
            "alignment": "Literal notebook behaviour; forecast is 147 hours earlier than target windows.",
            "comparison_status": "Do not compare directly with LSTM; diagnostic source-fidelity result.",
            "interval_nominal_percent": 80.0,
            "forecast_origins": num_origins,
            "fit_seconds": fit_seconds,
            **literal_metrics,
        },
        {
            "model": "Facebook Prophet",
            "protocol": "chronological_aligned_95pct",
            "alignment": "Forecast and target windows have identical timestamps.",
            "comparison_status": "Indicative versus LSTM only: Prophet saw first 80%, LSTM used 60/20/20.",
            "interval_nominal_percent": 95.0,
            "forecast_origins": num_origins,
            "fit_seconds": fit_seconds,
            **aligned_metrics,
        },
    ]
    summary = add_mw_columns(pd.DataFrame(rows), global_range)
    literal_horizon.insert(0, "protocol", "paper_literal_80pct")
    literal_horizon.insert(1, "interval_nominal_percent", 80.0)
    aligned_horizon.insert(0, "protocol", "chronological_aligned_95pct")
    aligned_horizon.insert(1, "interval_nominal_percent", 95.0)

    continuous = pd.DataFrame(
        {
            "timestamp": test_index,
            "actual_MW": raw[target].iloc[split_at:].to_numpy(),
            "prediction_MW": yhat_95 * global_range + global_min,
            "lower_95_MW": lower_95 * global_range + global_min,
            "upper_95_MW": upper_95 * global_range + global_min,
        }
    )
    aligned_start = history
    first_day = pd.DataFrame(
        {
            "timestamp": test_index[aligned_start : aligned_start + horizon],
            "actual_MW": raw[target].iloc[split_at + aligned_start : split_at + aligned_start + horizon].to_numpy(),
            "prediction_MW": aligned_prediction[0] * global_range + global_min,
            "lower_95_MW": aligned_lower[0] * global_range + global_min,
            "upper_95_MW": aligned_upper[0] * global_range + global_min,
        }
    )

    # The LSTM value is kept in a separate comparison file because its scaler and
    # training split differ.  Both models are expressed in MW there.
    lstm_train_end = int(len(raw) * float(config["train_split"]))
    lstm_range = float(raw[target].iloc[:lstm_train_end].max() - raw[target].iloc[:lstm_train_end].min())
    lstm_reference = read_lstm_reference(args.lstm_metrics, lstm_range)
    comparison = pd.concat(
        [pd.DataFrame([lstm_reference]), summary.loc[summary["protocol"] == "chronological_aligned_95pct"]],
        ignore_index=True,
        sort=False,
    )

    summary.to_csv(args.output_dir / "prophet_protocol_metrics.csv", index=False)
    pd.concat([literal_horizon, aligned_horizon], ignore_index=True).to_csv(
        args.output_dir / "prophet_metrics_by_horizon.csv", index=False
    )
    continuous.to_csv(args.output_dir / "prophet_continuous_test_forecast_95_MW.csv", index=False)
    first_day.to_csv(args.output_dir / "prophet_first_aligned_24h_MW.csv", index=False)
    comparison.to_csv(args.output_dir / "lstm_vs_prophet_indicative_MW.csv", index=False)
    save_first_day_plot(first_day, args.output_dir / "prophet_first_aligned_24h.png")
    (args.output_dir / "prophet_model.json").write_text(model_to_json(model), encoding="utf-8")

    metadata = {
        "data_file": str(args.data.resolve()),
        "data_sha256": sha256(args.data),
        "config_file": str(args.config.resolve()),
        "config_sha256": sha256(args.config),
        "source_notebook": "paper_source/notebooks/Train and Benchmark Models.ipynb",
        "source_cell_summary": "m = Prophet(); fit first 80%; one continuous hourly forecast; sliding 24-hour windows.",
        "target": target,
        "rows_total": len(raw),
        "paper_train_rows": len(train),
        "paper_test_rows": len(test_index),
        "paper_train_end": str(raw.index[split_at - 1]),
        "paper_test_start": str(test_index[0]),
        "history_horizon_hours": history,
        "forecast_horizon_hours": horizon,
        "forecast_origins": num_origins,
        "paper_max_origins": PAPER_MAX_ORIGINS,
        "scaling": "Min-Max fitted on full data before the 80/20 split, following the notebook exactly.",
        "paper_literal_interval": "Prophet default 80% interval; source-fidelity diagnostic only.",
        "aligned_interval": "Prophet 95% interval; timestamp-aligned comparison output.",
        "alignment_warning": "The frozen notebook compares Prophet's windows starting at the test split to TimeSeriesData targets beginning after 147 history hours. The aligned output fixes that timestamp offset without refitting Prophet.",
        "lstm_comparison_warning": "Existing LSTM used 60/20/20 and training-only target scaling; Prophet notebook uses 80/20 and full-data scaling. Compare MW scores only as indicative.",
        "prophet_version": __import__("prophet").__version__,
        "fit_seconds": fit_seconds,
        "predict_seconds": predict_seconds,
    }
    (args.output_dir / "run_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    print("Prophet paper protocol completed.")
    print(summary[["protocol", "Rmse", "Mae", "Picp", "Sharpness", "Mis", "fit_seconds"]].to_string(index=False))
    print(f"Output directory: {args.output_dir}")


if __name__ == "__main__":
    main()
